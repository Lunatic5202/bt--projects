/**
 * Website enquiry submissions from the contact form.
 */
export const enquiries = mysqlTable("enquiries", {
  id: int("id").autoincrement().primaryKey(),
  name: varchar("name", { length: 160 }).notNull(),
  email: varchar("email", { length: 320 }).notNull(),
  phone: varchar("phone", { length: 32 }),
  company: varchar("company", { length: 160 }),
  serviceType: varchar("serviceType", { length: 80 }).notNull().default("Not specified"),
  projectStage: varchar("projectStage", { length: 80 }).notNull().default("Not specified"),
  siteLocation: varchar("siteLocation", { length: 255 }),
  message: text("message").notNull(),
  createdAt: timestamp("createdAt").defaultNow().notNull(),
});

export type Enquiry = typeof enquiries.$inferSelect;
export type InsertEnquiry = typeof enquiries.$inferInsert;
